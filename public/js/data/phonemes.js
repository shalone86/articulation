/** All practice words for a phoneme card, key word first. */
export function phonemeWords(p) {
  const list = p.words ?? [
    ...(p.positions?.initial ?? []),
    ...(p.positions?.medial ?? []),
    ...(p.positions?.final ?? []),
  ];
  return [p.key, ...list.filter((w) => w !== p.key)];
}
